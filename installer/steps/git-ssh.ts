import * as p from '@clack/prompts';
import { mkdirSync } from 'node:fs';
import { hostname } from 'node:os';
import { join } from 'node:path';
import { exists, readText, writeFile } from '../lib/fs.ts';
import { PRIVATE_ENV } from '../lib/private.ts';
import { storeSecret } from '../lib/secrets.ts';
import { plan, stow } from '../lib/stow.ts';
import type { Ctx, Step } from '../types.ts';

interface Key {
  label: string;
  file: string;
  email: string;
}

const keys = (ctx: Ctx): Key[] => {
  const { GIT_EMAIL, WORK_GIT_EMAIL, WORK_SSH_KEY } = ctx.env;
  const list: Key[] = [];
  if (GIT_EMAIL) list.push({ label: 'personal', file: join(ctx.home, '.ssh/id_ed25519'), email: GIT_EMAIL });
  if (WORK_GIT_EMAIL) list.push({ label: 'work', file: join(ctx.home, '.ssh', WORK_SSH_KEY || 'work_ed25519'), email: WORK_GIT_EMAIL });
  return list;
};

/** ~/.gitconfig.local: identity + includeIf for work repos (never committed). */
function gitLocal(ctx: Ctx): string | undefined {
  const { GIT_NAME, GIT_EMAIL, WORK_GIT_NAME, WORK_GIT_EMAIL, WORK_DIR } = ctx.env;
  if (!GIT_NAME || !GIT_EMAIL) return undefined;
  const lines = ['# Generated by setthemacup from private.env — edit that file, not this one.', '[user]', `\tname = ${GIT_NAME}`, `\temail = ${GIT_EMAIL}`];
  if (WORK_GIT_EMAIL && WORK_DIR) {
    lines.push(`[includeIf "gitdir:${WORK_DIR.replace(/\/?$/, '/')}"]`, '\tpath = ~/.gitconfig.work');
  }
  return `${lines.join('\n')}\n`;
}

const gitWork = (ctx: Ctx) =>
  `# Generated by setthemacup from private.env.\n[user]\n\tname = ${ctx.env.WORK_GIT_NAME || ctx.env.WORK_GIT_EMAIL}\n\temail = ${ctx.env.WORK_GIT_EMAIL}\n`;

/** ~/.ssh/config.local: the work GitHub host alias (never committed). */
function sshLocal(ctx: Ctx): string {
  const { WORK_GIT_EMAIL, WORK_SSH_HOST, WORK_SSH_KEY } = ctx.env;
  const lines = ['# Generated by setthemacup from private.env.'];
  if (WORK_GIT_EMAIL && WORK_SSH_HOST) {
    lines.push(`Host ${WORK_SSH_HOST}`, '    HostName github.com', '    User git', `    IdentityFile ~/.ssh/${WORK_SSH_KEY || 'work_ed25519'}`);
  }
  return `${lines.join('\n')}\n`;
}

const ghLoggedIn = async (ctx: Ctx) => ctx.sh.ok('gh', ['auth', 'status', '--hostname', 'github.com']);

async function uploaded(ctx: Ctx, key: Key): Promise<boolean> {
  const pub = readText(`${key.file}.pub`)?.split(' ').slice(0, 2).join(' ');
  const listed = await ctx.sh.capture('gh', ['ssh-key', 'list']);
  return Boolean(pub && listed.ok && listed.stdout.includes(pub.split(' ')[1]!));
}

/** Adding SSH keys needs the admin:public_key scope, which a default gh login lacks */
const SCOPE = 'admin:public_key';
const hasScope = async (ctx: Ctx) => {
  const r = await ctx.sh.capture('gh', ['auth', 'status', '--active', '--hostname', 'github.com']);
  return r.ok && `${r.stdout}${r.stderr}`.includes(SCOPE);
};

/** Log in when needed (always for the work account), add the key, then switch back to `restoreUser`. */
async function upload(ctx: Ctx, key: Key, opts: { login: boolean; restoreUser?: string }): Promise<void> {
  if (opts.login) {
    await ctx.interactive(`Log in to GitHub (${key.label} account) in your browser`, () =>
      ctx.sh.run('gh', ['auth', 'login', '--hostname', 'github.com', '--git-protocol', 'ssh', '--skip-ssh-key', '--web', '--scopes', SCOPE], {
        interactive: true,
      }),
    );
  } else if (!(await hasScope(ctx))) {
    await ctx.interactive(`Allow gh to add SSH keys (${key.label} account) — approve in your browser`, () =>
      ctx.sh.run('gh', ['auth', 'refresh', '--hostname', 'github.com', '--scopes', SCOPE], { interactive: true }),
    );
  }
  await ctx.task(`Upload ${key.label} SSH key`, async () => {
    if (await uploaded(ctx, key)) return 'already on GitHub';
    await ctx.sh.run('gh', ['ssh-key', 'add', `${key.file}.pub`, '--title', `${hostname().split('.')[0]} (${key.label})`]);
  });
  if (opts.restoreUser) {
    await ctx.sh.run('gh', ['auth', 'switch', '--hostname', 'github.com', '--user', opts.restoreUser], { allowFail: true });
  }
}

/** Ask for a passphrase (twice), create the key, and store the passphrase in the Keychain. */
async function createKey(ctx: Ctx, key: Key): Promise<void> {
  let passphrase = '';
  for (;;) {
    const first = await p.password({ message: `Passphrase for your new ${key.label} SSH key (saved in Keychain)`, validate: (v) => (v && v.length >= 8 ? undefined : 'At least 8 characters') });
    if (p.isCancel(first)) throw new Error('cancelled');
    const again = await p.password({ message: 'Same passphrase again' });
    if (p.isCancel(again)) throw new Error('cancelled');
    if (first === again) {
      passphrase = first;
      break;
    }
    p.log.warn("Those didn't match — try again.");
  }
  await ctx.task(`Create ${key.label} SSH key`, async () => {
    if (!ctx.dryRun) mkdirSync(join(ctx.home, '.ssh'), { recursive: true, mode: 0o700 });
    // -N puts the passphrase in argv for the few ms ssh-keygen runs; acceptable on a personal Mac
    await ctx.sh.run('ssh-keygen', ['-q', '-t', 'ed25519', '-C', key.email, '-f', key.file, '-N', passphrase]);
    // ssh-add reads the passphrase through lib/askpass instead of a terminal prompt
    await ctx.sh.run('ssh-add', ['--apple-use-keychain', key.file], {
      env: {
        SSH_ASKPASS: join(ctx.repo, 'installer/lib/askpass'),
        SSH_ASKPASS_REQUIRE: 'force',
        SETTHEMACUP_SECRET_FILE: storeSecret(`ssh-${key.label}`, passphrase),
      },
    });
    return key.file.replace(ctx.home, '~');
  });
}

export const gitSsh: Step = {
  id: 'git',
  title: 'Git + SSH',
  summary: 'Git identity (personal + work via includeIf), SSH keys, optional upload to GitHub',
  details: [
    '~/.gitconfig is stowed from dotfiles/git (delta pager, sane defaults, no identity)',
    '~/.gitconfig.local gets [user] from private.env plus an includeIf that switches to the work identity under $WORK_DIR',
    '~/.ssh/config is stowed; work host alias goes in ~/.ssh/config.local',
    'Up front: asks a passphrase for each new ed25519 key (stored in the macOS Keychain), then logs in with gh and uploads each key to its GitHub account',
  ],
  requires: ['gh', 'stow'],

  async check(ctx) {
    const todo: string[] = [];
    if (!exists(join(ctx.home, '.gitconfig.local'))) todo.push('git identity');
    for (const k of keys(ctx)) if (!exists(k.file)) todo.push(`${k.label} key`);
    const p = exists(join(ctx.home, '.ssh')) ? await plan(ctx, 'ssh', { noFolding: true }) : { links: 1, conflicts: [] };
    if (p.links || p.conflicts.length) todo.push('ssh config');
    if (!ctx.env.GIT_EMAIL) return { state: 'missing', detail: 'GIT_NAME/GIT_EMAIL missing in private.env' };
    return todo.length ? { state: todo.length >= 3 ? 'missing' : 'partial', detail: `to do: ${todo.join(', ')}` } : { state: 'done', detail: 'configured' };
  },

  async run(ctx) {
    await ctx.task('Git identity (~/.gitconfig.local)', async () => {
      const local = gitLocal(ctx);
      if (!local) throw new Error(`set GIT_NAME and GIT_EMAIL in ${PRIVATE_ENV}`);
      writeFile(ctx, join(ctx.home, '.gitconfig.local'), local);
      if (ctx.env.WORK_GIT_EMAIL) writeFile(ctx, join(ctx.home, '.gitconfig.work'), gitWork(ctx));
      return ctx.env.WORK_GIT_EMAIL ? `personal + work under ${ctx.env.WORK_DIR}` : 'personal';
    });

    await ctx.task('SSH config', async () => {
      const dir = join(ctx.home, '.ssh');
      // Must exist first: otherwise stow would fold ~/.ssh into a link to the repo, and keys would land in git
      if (!ctx.dryRun) mkdirSync(dir, { recursive: true, mode: 0o700 });
      writeFile(ctx, join(dir, 'config.local'), sshLocal(ctx), 0o600);
      return stow(ctx, 'ssh', { noFolding: true });
    });

    await ctx.task('SSH keys', async () => {
      const list = keys(ctx);
      const missing = list.filter((k) => !exists(k.file)).map((k) => k.label);
      if (missing.length) throw new Error(`missing ${missing.join(', ')} key — run \`setup --only git\` to create it`);
      return list.length ? list.map((k) => k.label).join(' + ') : 'none (no email in private.env)';
    });
  },

  /** Question phase: passphrases for new keys, then GitHub logins and key uploads. */
  async prepare(ctx) {
    const list = keys(ctx);
    const missing = list.filter((k) => !exists(k.file));
    if (missing.length && ctx.yes) ctx.warn('New SSH keys need a passphrase; skipped under --yes. Run `setup --only git`.');
    else for (const key of missing) await createKey(ctx, key);

    const have = list.filter((k) => exists(k.file) || ctx.dryRun);
    if (ctx.yes || !have.length || !(await ctx.confirm('Upload SSH keys to GitHub (browser login)?', true))) return;
    const [personal, work] = have;
    if (personal) await upload(ctx, personal, { login: !(await ghLoggedIn(ctx)) });
    if (work && (await ctx.confirm('Upload the work key too (logs in to your work GitHub account)?', true))) {
      await upload(ctx, work, { login: true, restoreUser: ctx.env.GIT_NAME });
    }
  },

  async nextSteps(ctx) {
    const steps: string[] = [];
    const personal = keys(ctx)[0];
    if (personal && !((await ghLoggedIn(ctx)) && (await uploaded(ctx, personal)))) {
      steps.push('Upload SSH keys: `gh auth login`, then `gh ssh-key add ~/.ssh/id_ed25519.pub` (work key: log in to the work account)');
    }
    steps.push('Test: `ssh -T git@github.com`' + (ctx.env.WORK_SSH_HOST && ctx.env.WORK_GIT_EMAIL ? ` and \`ssh -T git@${ctx.env.WORK_SSH_HOST}\`` : ''));
    return steps;
  },
};
